def strategy_bonus(
    school_name: str,
    profession: str = "",
    student_goal: Optional[str] = None,
    family_bg: Optional[str] = None,
) -> dict:
    """计算策略加权(返回各项明细,用于前端展示 + 总分)

    Args:
        school_name: 校名(暂未使用,保留)
        profession: 专业名(从 group_id 或表里读,先支持专业级)
        student_goal: 考公/考研/就业/考编/稳定/兴趣
        family_bg: 富裕/普通/困难

    Returns:
        {
            "goal_bonus": 25,        # 学生目标 → 专业加
            "family_penalty": -10,   # 家庭背景 → 天坑减
            "ai_impact_warn": 0.85,  # AI 冲击度 (0-1,给前端展示用)
            "total": 15,             # 实际叠加的排序权重
        }
    """
    goal_b = 0
    if student_goal and profession:
        goal_b = GOAL_PROFESSION_BONUS.get(student_goal, {}).get(profession, 0)

    family_p = 0
    if family_bg and profession:
        family_p = FAMILY_PENALTY.get(family_bg, {}).get(profession, 0)

    ai = AI_IMPACT.get(profession, 0.5)  # 未知默认中风险

    # 排序时只用 (goal + family) 之和
    total = goal_b + family_p

    return {
        "goal_bonus": goal_b,
        "family_penalty": family_p,
        "ai_impact_warn": round(ai, 2),
        "ai_impact_label": _ai_label(ai),
        "total": total,
    }


def _ai_label(score: float) -> str:
    if score < 0.3:
        return "低(难替代)"
    if score < 0.6:
        return "中(部分场景受影响)"
    return "高(慎选,需深度规划)"


