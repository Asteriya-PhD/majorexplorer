import json
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent.parent
CUR = ROOT / "skills/gaokao-major-explorer/data/curated"
print(f"[hand_curate_p4] CUR = {CUR}")


def apply(slug, *, top_schools, employment_direction, alumni_quotes, pitfalls, who_fits_yes, who_fits_no, lede, summary):
    p = CUR / f"{slug}.json"
    d = json.loads(p.read_text())
    d["top_schools"] = top_schools
    d["employment_direction"] = employment_direction
    d["alumni_quotes"] = alumni_quotes
    if "overview_v2" not in d:
        d["overview_v2"] = {}
    d["overview_v2"]["pitfalls"] = pitfalls
    d["overview_v2"]["who_fits_yes"] = who_fits_yes
    d["overview_v2"]["who_fits_no"] = who_fits_no
    d["overview_v2"]["lede"] = lede
    d["summary"] = summary
    p.write_text(json.dumps(d, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"OK {slug}")


