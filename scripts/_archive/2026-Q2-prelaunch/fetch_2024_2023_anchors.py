# ─────────────────────────────────────────
# 合成
# ─────────────────────────────────────────
def build_year_admission(year: int, subject: str, anchors: list, year_offset_from_2025: int) -> pd.DataFrame:
    """用锚点(权威) + 2025 基础(填空)合成
    - 锚点里的 (school, group) → 真实
    - 锚点没覆盖的(2025 基础里有)→ 用 2025 + 波动合成
    """
    # 1. 加载 2025 基础(已知全)
    base_2025 = pd.read_csv(DATA_DIR / f"hubei_admission_{subject}_2025.csv")
    # 2. 锚点转为 dict
    anchor_dict = {(s, g): (sc, r) for s, g, sc, r in anchors}

    rows = []
    # 2.1 锚点里的权威数据
    for s, g, sc, r in anchors:
        # 从 2025 基础找类型/学费/选科等元数据
        match = base_2025[(base_2025["school_name"] == s) & (base_2025["group_id"] == g)]
        if not match.empty:
            meta = match.iloc[0]
            rows.append({
                "year": year, "subject": subject, "school_name": s, "school_type": meta["school_type"],
                "group_id": g, "xuanke_req": meta["xuanke_req"], "xuanke_subjects": meta["xuanke_subjects"],
                "plan_count": meta["plan_count"], "min_score": sc, "min_rank": r,
                "tuition_yuan": meta["tuition_yuan"], "city": meta["city"],
                "is_special": meta["is_special"], "data_source": "真实锚点",
            })
        else:
            # 锚点里的校 2025 基础没收录,需要从 2023 历史 / 湖北 招办公布查
            # 简化: 类型推断
            if any(x in s for x in ["清华", "北大", "复旦", "上交", "中科大", "人大", "南开", "中科院", "同济", "西交", "哈工大", "北航", "北理工", "人民大学", "南大", "东南", "武大", "华科", "中大", "华南理工", "山大", "重大", "中南", "湖南", "川大", "电子科大", "西电", "西北工大", "中央民族", "中农", "兰大", "中国海洋"]):
                stype = "985"
            elif any(x in s for x in ["理工", "师范", "财经", "农业", "地质", "邮电", "交通", "矿业"]):
                stype = "211"
            else:
                stype = "普通"
            rows.append({
                "year": year, "subject": subject, "school_name": s, "school_type": stype,
                "group_id": g, "xuanke_req": "物理+化学" if subject == "物理" else "历史+不限",
                "xuanke_subjects": "物理|化学" if subject == "物理" else "历史",
                "plan_count": 30, "min_score": sc, "min_rank": r,
                "tuition_yuan": 6000, "city": "其他", "is_special": "否",
                "data_source": "真实锚点",
            })
    # 2.2 2025 基础里但锚点没覆盖的 → 合成
    anchor_pairs = set(anchor_dict.keys())
    for _, row in base_2025.iterrows():
        school = row["school_name"]
        group = row["group_id"]
        if (school, group) in anchor_pairs:
            continue  # 已有
        # 合成
        year_shift = year_offset_from_2025 * 3
        score = max(150, int(row["min_score"]) + year_shift)
        rank = int(row["min_rank"]) + (year_offset_from_2025 * 3000)
        rows.append({
            "year": year, "subject": subject, "school_name": school, "school_type": row["school_type"],
            "group_id": group, "xuanke_req": row["xuanke_req"], "xuanke_subjects": row["xuanke_subjects"],
            "plan_count": row["plan_count"], "min_score": score, "min_rank": rank,
            "tuition_yuan": row["tuition_yuan"], "city": row["city"],
            "is_special": row["is_special"], "data_source": "合成(基于2025+波动)",
        })
    return pd.DataFrame(rows)


def main():
    cases = [
        (2024, "物理", ANCHORS_2024_物理, -1),
        (2024, "历史", ANCHORS_2024_历史, -1),
        (2023, "物理", ANCHORS_2023_物理, -2),
        (2023, "历史", ANCHORS_2023_历史, -2),
    ]

    for year, subject, anchors, offset in cases:
        print(f"\n{'='*60}")
        print(f"📥 生成 {year} 湖北 {subject} 投档表 (锚点 {len(anchors)} 条 + 2025 合成)")
        print(f"{'='*60}")
        df = build_year_admission(year, subject, anchors, offset)
        real_count = (df["data_source"] == "真实锚点").sum()
        print(f"  真实锚点: {real_count}/{len(df)} = {real_count/len(df):.1%}")
        print(f"  合成部分:  {len(df)-real_count}/{len(df)} = {(len(df)-real_count)/len(df):.1%}")

        target = DATA_DIR / f"hubei_admission_{subject}_{year}.csv"
        if target.exists():
            backup = LOG_DIR / f"{target.stem}_backup_{datetime.now().strftime('%Y%m%d_%H%M%S')}.csv"
            target.rename(backup)
            print(f"  📦 旧文件备份: {backup.name}")
        df.to_csv(target, index=False)
        print(f"  ✅ 写入 {target.name} ({len(df)} 行)")

    print(f"\n{'='*60}")
    print("⚠️  限制说明")
    print("  2024/2023 数据 = 真实锚点(2024物理 ~50,2024历史 ~30) + 合成部分")
    print("  真实锚点覆盖: 985 完整 + 211 部分 + 本省本科")
    print("  合成部分: 普通本科 + 专科,按 2025 + 波动估算")
    print("  生产前需替换为湖北省教育考试院官方 PDF/Excel")
    print(f"{'='*60}")


if __name__ == "__main__":
    main()
